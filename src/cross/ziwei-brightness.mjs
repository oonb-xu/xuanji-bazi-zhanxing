/** 二十八宿的起点黄经（以角宿起点为基准，累加得到） */
export function xiuRanges(startLon = 0) {
  let cur = startLon;
  return XIU28.map((x) => {
    const from = cur % 360;
    cur += x.deg;
    return { ...x, from, to: cur % 360 };
  });
}

/** 给定黄经，查出落在哪一宿 */
export function xiuOf(lon, startLon = 0) {
  const ranges = xiuRanges(startLon);
  const d = ((lon % 360) + 360) % 360;
  for (const r of ranges) {
    const span = ((r.to - r.from) + 360) % 360 || 360;
    const off = ((d - r.from) + 360) % 360;
    if (off < span) return { name: r.name, offset: Math.round(off * 100) / 100, span: Math.round(span * 100) / 100 };
  }
  return null;
}

/**
 * 紫微亮度：给定主星与地支
 * @returns {level, factor, note}
 */
export function ziweiBrightness(star, zhi) {
  const row = ZIWEI_BRIGHTNESS[star];
  const i = ZHI12.indexOf(zhi);
  if (!row || i < 0) return null;
  const level = row[i];
  // 与 system-advantages 的 brightnessFactor 保持一致
  const M = { 庙: 1.30, 旺: 1.18, 得地: 1.08, 利: 1.00, 平: 0.95, 不得地: 0.88, 陷: 0.78 };
  return {
    level,
    factor: M[level] ?? 1.0,
    note: '紫微亮度属**偶然层**加乘，不替代本质尊贵；本表**待校**（他派可能有差异）',
  };
}

