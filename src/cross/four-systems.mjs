/** 把任意体系的技术名词翻译成「十神 + 白话」 */
export function translate(term) {
  if (!term) return null;
  const t = String(term);

  if (QIZHENG[t]) return { system: '七政四余', as: QIZHENG[t].planet, ...plainOf(QIZHENG[t].planet), note: QIZHENG[t].note };
  if (SIYU[t]) return { system: '七政四余·四余', as: SIYU[t].calc, tg: '—', plain: SIYU[t].note, note: SIYU[t].graha };
  if (ZIWEI_STARS[t]) return { system: '紫微斗数', as: t, tg: ZIWEI_STARS[t].tg, plain: ZIWEI_STARS[t].plain, note: '对应占星：' + ZIWEI_STARS[t].astro };
  if (SIHUA[t]) return { system: '紫微斗数·四化', as: t, tg: SIHUA[t].tg, plain: SIHUA[t].plain };

  const SIGNS = ['白羊', '金牛', '双子', '巨蟹', '狮子', '处女', '天秤', '天蝎', '射手', '摩羯', '水瓶', '双鱼'];
  if (SIGNS.includes(t)) {
    const yj = Object.entries(ZHI_SIGN.yuejiang).find(([, v]) => v === t);
    const mj = Object.entries(ZHI_SIGN.yuejian).find(([, v]) => v === t);
    return { system: '占星/七政四余', as: t, tg: '—', plain: `黄道 30° 段，位于${t}`, note: `月将作「${yj?.[0] ?? '?'}」・月建作「${mj?.[0] ?? '?'}」` };
  }
  return null;
}

