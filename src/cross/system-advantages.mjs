/**
 * 给一颗行星算出「四系统合议」的完整画像
 * @param planet {name, sign, house, lon, retro}
 * @param ctx {dignity, accidental, tenGod, ziweiBrightness, xiu, siyu}
 */
export function synthesize(planet, ctx = {}) {
  if (!planet) return null;
  const out = {
    planet: planet.name,
    layers: [],
  };
  const push = (system, aspect, value) => out.layers.push({ system, aspect, value });

  push('坐标层', '黄经/星座', `${planet.sign} ${planet.deg ?? '?'}°`);
  if (ctx.dignity) push('本质层(占星)', '本质尊贵', `${ctx.dignity.tier} ×${ctx.dignity.k}`);
  if (ctx.accidental) push('偶然层(占星)', '宫位/合轴', `第${planet.house}宫 ${ctx.accidental}`);
  if (ctx.ziweiBrightness) push('偶然层(紫微)', '星×宫亮度', `${ctx.ziweiBrightness}（作为额外乘子）`);
  if (ctx.tenGod) push('关系层(八字)', '十神', `${ctx.tenGod.group} ${(ctx.tenGod.w * 100).toFixed(0)}%`);
  if (ctx.domain) push('领域层', '生活领域', ctx.domain);
  if (ctx.xiu) push('细分层(七政)', '二十八宿', ctx.xiu);
  if (planet.retro) push('偶然层(占星)', '顺逆', '逆行（力量内化）');

  // ★★ 双轴模型（用户 2026-10-28 纠正）：
  //   「一个主心理一个主物质」——不是冲突，是两个不同的测量轴。
  //
  //   结构依据（不是事后解释）：
  //     紫微庙旺 = f(星, **宫位**)，而紫微的宫位是财帛/官禄/田宅/疾厄…**全是生活事项**
  //               ⇒ 物质属性刻在它的数据结构里
  //     占星尊贵 = f(星, **星座**)，星座是**性质**不是事项
  //               ⇒ 心理属性刻在它的数据结构里
  //
  //   所以两者可以同时成立、方向相反，且**都有意义**：
  //     月亮天蝎「落」＋ 太阴亥「庙」 ⇒ 心里不安，但物质有靠。
  const psychK = ctx.dignity?.k ?? 1;
  const zwLevel = ctx.ziweiBrightness;
  const materialK = zwLevel ? brightnessFactor(zwLevel) : 1;

  out.axes = {
    // 心理轴：占星本质尊贵（这颗星本身多好地行使职能）
    psych: {
      source: '古典占星·本质尊贵',
      basis: ctx.dignity ? `${planet.sign} → ${ctx.dignity.tier}` : '无',
      value: Math.round(psychK * 1000) / 1000,
      level: psychK >= 1.3 ? '强' : psychK >= 1.05 ? '中偏强' : psychK >= 0.95 ? '中' : psychK >= 0.7 ? '偏弱' : '弱',
    },
    // 物质轴：紫微星×宫亮度（这件事在你生活里能发挥多少）
    material: {
      source: '紫微斗数·星宫亮度',
      basis: zwLevel ? `${ctx.ziweiStar ?? '对应主星'} 在 ${ctx.ziweiZhi ?? '?'} 为 ${zwLevel}` : '无',
      value: Math.round(materialK * 1000) / 1000,
      level: materialK >= 1.2 ? '旺' : materialK >= 1.05 ? '中偏旺' : materialK >= 0.95 ? '平' : materialK >= 0.85 ? '偏弱' : '弱',
    },
  };

  // 象限判定：两个轴各自独立，不合并成一个数
  const q = `${out.axes.psych.level}|${out.axes.material.level}`;
  out.quadrant = {
    psych: out.axes.psych.level,
    material: out.axes.material.level,
    reading: quadrantReading(psychK, materialK),
    note: '两轴独立给值，**不相乘、不平均**。心理与物质可以同时一强一弱，这是有效信息而非矛盾。',
  };
  out.strengthHint = null;   // 不再给单一"强度"，避免把两轴压成一个数

  out.note = '心理轴取占星本质尊贵，物质轴取紫微星宫亮度；两者是不同测量轴，方向相反也各自成立。';
  return out;
}

/**
 * 双轴象限的白话读法
 * 心理轴 = 占星本质尊贵；物质轴 = 紫微亮度
 */
export function quadrantReading(psychK, materialK) {
  const p = psychK >= 1.05, m = materialK >= 1.05;
  if (p && m) return '心理顺畅，物质也顺 —— 里外都好';
  if (p && !m) return '心理顺畅，但物质上不显 —— 心里有底，现实缺位';
  if (!p && m) return '物质有靠，但心里不安 —— 现实稳，情绪拧';
  return '心理不顺，物质也弱 —— 两头都要补';
}

/** 紫微七级亮度 → 乘子（明确标注：这是**偶然层**加乘，不替代本质尊贵） */
export function brightnessFactor(level) {
  const M = { 庙: 1.30, 旺: 1.18, 得地: 1.08, 利: 1.00, 平: 0.95, 不得地: 0.88, 陷: 0.78 };
  return M[level] ?? 1.0;
}

